import { createClient } from '@supabase/supabase-js';
import { createHash } from 'crypto';
import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

const SUPABASE_URL =
process.env.SUPABASE_URL ||
process.env.NEXT_PUBLIC_SUPABASE_URL;

const SERVICE_ROLE_KEY =
process.env.SUPABASE_SERVICE_ROLE_KEY ||
process.env.SUPABASE_SERVICE_KEY;

const ELEVENLABS_API_KEY = process.env.ELEVENLABS_API_KEY;

if (!SUPABASE_URL || !SERVICE_ROLE_KEY) {
throw new Error('Missing Supabase environment variables.');
}

if (!ELEVENLABS_API_KEY) {
throw new Error('Missing ELEVENLABS_API_KEY.');
}

const supabaseAdmin = createClient(
SUPABASE_URL,
SERVICE_ROLE_KEY,
{
auth: {
autoRefreshToken: false,
persistSession: false,
},
}
);

function getHeaders() {
return {
'Cache-Control': 'private, no-store, max-age=0',
'Access-Control-Allow-Origin': '*',
'Access-Control-Allow-Headers': 'x-api-key, Content-Type',
'Access-Control-Allow-Methods': 'POST, OPTIONS',
'Vary': 'Origin',
};
}

function jsonResponse(
data: Record<string, unknown>,
status = 200
) {
return NextResponse.json(data, {
status,
headers: getHeaders(),
});
}

export async function POST(req: NextRequest) {
try {
// =====================================
// 1. CUSTOMER API KEY AUTHENTICATION
// =====================================

const apiKey =
  req.headers.get('x-api-key')?.trim() || '';

if (!apiKey) {
  return jsonResponse({
    success: false,
    error: 'Missing x-api-key header.',
  }, 401);
}

// Keys generated by Main Naija Pidgin use mnp_ + 48 hex characters.
if (!/^mnp_[a-f0-9]{48}$/i.test(apiKey)) {
  return jsonResponse({
    success: false,
    error: 'Invalid API key format.',
  }, 401);
}

// Hash the customer's raw key.
// Never search the database using the raw customer key.
const keyHash = createHash('sha256')
  .update(apiKey)
  .digest('hex');

const {
  data: keyData,
  error: keyError,
} = await supabaseAdmin
  .from('api_keys')
  .select('id, is_active')
  .eq('key_hash', keyHash)
  .maybeSingle();

if (keyError) {
  console.error('API key lookup failed:', keyError.message);

  return jsonResponse({
    success: false,
    error: 'API authentication temporarily unavailable.',
  }, 503);
}

if (!keyData || keyData.is_active !== true) {
  return jsonResponse({
    success: false,
    error: 'Invalid or inactive API key.',
  }, 401);
}

// =====================================
// 2. VALIDATE REQUEST BODY
// =====================================

let body: any;

try {
  body = await req.json();
} catch {
  return jsonResponse({
    success: false,
    error: 'Invalid JSON request body.',
  }, 400);
}

const text =
  typeof body.text === 'string'
    ? body.text.trim()
    : '';

const voiceId =
  typeof body.voiceId === 'string'
    ? body.voiceId.trim()
    : '';

if (text.length < 3) {
  return jsonResponse({
    success: false,
    error: 'Text is required (minimum 3 characters).',
  }, 400);
}

if (text.length > 5000) {
  return jsonResponse({
    success: false,
    error: 'Text exceeds the 5000 character limit.',
  }, 400);
}

if (!voiceId) {
  return jsonResponse({
    success: false,
    error: 'voiceId is required.',
  }, 400);
}

// =====================================
// 3. VERIFY AUTHORIZED CHAIRMAN VOICE
// =====================================

const {
  data: registeredVoice,
  error: voiceError,
} = await supabaseAdmin
  .from('chairman_voices')
  .select('elevenlabs_voice_id')
  .eq('elevenlabs_voice_id', voiceId)
  .maybeSingle();

if (voiceError) {
  console.error('Voice lookup failed:', voiceError.message);

  return jsonResponse({
    success: false,
    error: 'Voice verification temporarily unavailable.',
  }, 503);
}

if (!registeredVoice) {
  return jsonResponse({
    success: false,
    error: 'This voice is not registered or authorized.',
  }, 403);
}

// =====================================
// 4. GENERATE HIGH QUALITY ELEVENLABS AUDIO
// =====================================

const ttsResponse = await fetch(
  `https://api.elevenlabs.io/v1/text-to-speech/${encodeURIComponent(voiceId)}?output_format=mp3_44100_192`,
  {
    method: 'POST',

    headers: {
      'xi-api-key': ELEVENLABS_API_KEY,
      'Content-Type': 'application/json',
      'Accept': 'audio/mpeg',
    },

    body: JSON.stringify({
      text,

      model_id: 'eleven_multilingual_v2',

      voice_settings: {
        stability: 0.35,
        similarity_boost: 0.85,
        style: 0.65,
        use_speaker_boost: true,
      },
    }),
  }
);

if (!ttsResponse.ok) {
  const providerStatus = ttsResponse.status;

  console.error(
    'ElevenLabs TTS failed:',
    providerStatus,
    await ttsResponse.text()
  );

  return jsonResponse({
    success: false,
    error: 'Voice generation failed. Please try again.',
  }, providerStatus === 429 ? 429 : 502);
}

const audioBuffer = await ttsResponse.arrayBuffer();

if (audioBuffer.byteLength === 0) {
  return jsonResponse({
    success: false,
    error: 'ElevenLabs returned empty audio.',
  }, 502);
}

// =====================================
// 5. ATOMIC CREDIT DEDUCTION
// =====================================

// Generate audio first.
// Only deduct after ElevenLabs successfully generates it.
const {
  data: deductionResult,
  error: deductionError,
} = await supabaseAdmin.rpc(
  'atomic_credit_deduct',
  {
    p_key_id: keyData.id,
    p_amount: 1,
  }
);

if (deductionError) {
  console.error(
    'Atomic credit deduction failed:',
    deductionError.message
  );

  // CRITICAL:
  // Never deliver paid audio if billing fails.
  return jsonResponse({
    success: false,
    error: 'Credit deduction failed. Audio was not delivered.',
  }, 503);
}

const deductionRow = Array.isArray(deductionResult)
  ? deductionResult[0]
  : deductionResult;

if (!deductionRow) {
  console.error('Credit deduction returned no result.');

  return jsonResponse({
    success: false,
    error: 'Unable to confirm credit deduction.',
  }, 503);
}

// =====================================
// 6. RETURN GENERATED AUDIO
// =====================================

const base64Audio = Buffer
  .from(audioBuffer)
  .toString('base64');

return jsonResponse({
  success: true,

  message: 'Main Naija Pidgin voice generated successfully.',

  audio_base64: base64Audio,

  audio_mime: 'audio/mpeg',

  credits: {
    remaining: deductionRow.credits_remaining,
    used: deductionRow.credits_used,
    total: deductionRow.credits_total,
  },
});

} catch (error) {
console.error('Speak API error:', error);

return jsonResponse({
  success: false,
  error: 'Internal server error.',
}, 500);

}
}

export async function OPTIONS() {
return new NextResponse(null, {
status: 204,
headers: getHeaders(),
});
}